def document(text: str, number: int = 1) -> Document:
    return read_document(DocumentId(f"d{number:02d}"), SourceFile("файл.txt", text))


def knowledge_base(*texts: str) -> KnowledgeBase:
    """Документы получают идентификаторы «d01», «d02»… в порядке аргументов."""
    return KnowledgeBase(
        tuple(document(text, number) for number, text in enumerate(texts, start=1))
    )
