def knowledge_base(texts: tuple[str, ...] = TEXTS) -> KnowledgeBase:
    return KnowledgeBase(
        tuple(
            read_document(DocumentId(f"d{index:02d}"), SourceFile(f"{index}.txt", text))
            for index, text in enumerate(texts, start=1)
        )
    )
