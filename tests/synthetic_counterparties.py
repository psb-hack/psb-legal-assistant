def _contract(title: str, dated: str, counterparty: str, roles: str, body: str) -> str:
    role, own_role = roles.split("/")
    return (
        f"{title}\n"
        f"г. Тверь — {dated} г.\n"
        f"{counterparty}, именуемое в дальнейшем «{role}», в лице директора, "
        "действующего на основании Устава, с одной стороны, и\n"
        f"ООО «Горизонт» (ИНН 6901000099), именуемое в дальнейшем «{own_role}», "
        "в лице директора, действующего на основании Устава, с другой стороны, "
        "заключили настоящий договор о нижеследующем.\n"
        "1. Предмет договора\n"
        f"1.1. {body}\n"
    )


