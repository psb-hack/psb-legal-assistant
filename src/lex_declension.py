"""Падежные формы слова из наименования по закрытой таблице окончаний.

Морфологических библиотек в сабмите нет. Формы порождаются от известной формы
именительного падежа, а слово из вопроса сравнивается с ними целиком: «трейдинг»
из «трейд» не получается, потому что «инг» — не окончание. Стеммер, который
срезает окончания с обеих сторон, склеивает «Гарант» с «Гарантия».
"""

from __future__ import annotations

import re

from lex_normalization import comparison_key

_MIN_DECLINED_LENGTH = 3
_MIN_STEM_LENGTH = 2

# Окончание именительного падежа → окончания всех падежей. Порядок — от длинных
# окончаний к коротким: «ия» проверяется раньше «я». Для названия во
# множественном числе формы единственного не порождаются.
_PARADIGMS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("ый", ("ый", "ого", "ому", "ым", "ом")),
    ("ой", ("ой", "ого", "ому", "ым", "ом", "оя", "ою", "оем", "ое")),
    (
        "ий",
        ("ий", "его", "ему", "ого", "ому", "им", "ем", "ом", "ия", "ию", "ием", "ии"),
    ),
    ("ая", ("ая", "ой", "ей", "ую", "ою", "ею")),
    ("яя", ("яя", "ей", "юю", "ею")),
    ("ое", ("ое", "ого", "ому", "ым", "ом")),
    ("ее", ("ее", "его", "ему", "им", "ем")),
    ("ые", ("ые", "ых", "ым", "ыми")),
    ("ие", ("ие", "их", "им", "ими", "ия", "ию", "ием", "ии")),
    ("ия", ("ия", "ии", "ию", "ией")),
    ("ии", ("ии", "ий", "иям", "иями", "иях")),
    ("ья", ("ья", "ьи", "ье", "ью", "ьей")),
    ("ье", ("ье", "ья", "ью", "ьем")),
    ("а", ("а", "ы", "и", "е", "у", "ой", "ей", "ою")),
    ("я", ("я", "и", "е", "ю", "ей", "ею")),
    ("о", ("о", "а", "у", "ом", "е")),
    ("е", ("е", "а", "я", "у", "ю", "ем")),
    ("ь", ("ь", "я", "ю", "ем", "е", "и", "ью")),
    ("й", ("й", "я", "ю", "ем", "е")),
    ("ы", ("ы", "", "ов", "ам", "ами", "ах")),
    (
        "и",
        ("и", "", "ей", "ев", "ов", "ий", "ям", "ам", "ями", "ами", "ях", "ах"),
    ),
)
_AFTER_CONSONANT = ("", "а", "у", "ом", "ем", "е")
# «городок» → «городка», «купец» → «купца»: гласная перед «к» и «ц» выпадает.
# Словаря нет, поэтому порождаются формы и с ней, и без неё.
_FLEETING_VOWEL = re.compile(r"[^аеиоуыэюя][ое][кц]")
# «альфа», но не «alfa» и не «склад3»: латиница и слова с цифрами не склоняются.
_CYRILLIC_WORD = re.compile(r"[а-я]+")


def case_forms(word: str) -> frozenset[str]:
    """Падежные формы слова в виде ключа сравнения; несклоняемое слово — оно само."""
    nominative = comparison_key(word)
    if (
        len(nominative) < _MIN_DECLINED_LENGTH
        or _CYRILLIC_WORD.fullmatch(nominative) is None
    ):
        return frozenset({nominative})
    for ending, endings in _PARADIGMS:
        stem = nominative.removesuffix(ending)
        if stem != nominative and len(stem) >= _MIN_STEM_LENGTH:
            return frozenset(stem + other for other in endings)
    forms = {nominative + ending for ending in _AFTER_CONSONANT}
    if _FLEETING_VOWEL.fullmatch(nominative[-3:]) is not None:
        shortened = nominative[:-2] + nominative[-1]
        forms.update(shortened + ending for ending in _AFTER_CONSONANT if ending)
    return frozenset(forms)
