_EXAMPLE_LAYOUT = """\
<пример>
Положения:
{provisions}
Вопрос: {question}
Ответ:
{answer}
</пример>"""
_EXAMPLE_PROVISION_LAYOUT = "{id} ({heading}): {text}"
_LINE_BREAK = "\n"


def _example_text(example: PromptExample) -> str:
    provisions = _LINE_BREAK.join(
        _EXAMPLE_PROVISION_LAYOUT.format(
            id=provision.id, heading=provision.heading, text=provision.text
        )
        for provision in example.provisions
    )
    return _EXAMPLE_LAYOUT.format(
        provisions=provisions,
        question=example.question,
        # Тот же вид, в каком ответ ждёт схема: поля в порядке генерации.
        answer=example.answer.model_dump_json(),
    )


# system одинаков для всех запросов: метка блоков и данные идут в сообщении
# пользователя, поэтому правила с примерами попадают в кэш префикса.
ANSWER_PROMPT_V1 = PromptRules(
    system=_LINE_BREAK.join(
        [ANSWER_RULES_V1, *(_example_text(example) for example in ANSWER_EXAMPLES_V1)]
    ),
    reminder=ANSWER_REMINDER_V1,
)
